void USBD_MIDI_DataInHandler(uint8_t *usb_rx_buffer, uint8_t usb_rx_buffer_length)
{
    uint8_t message, channel, nota, velocidad;

    while (usb_rx_buffer_length && *usb_rx_buffer != 0x00)
    {
        // Extraemos los datos del paquete MIDI
        message = usb_rx_buffer[1] >> 4;
        channel = usb_rx_buffer[1] & 0x0F;
        nota = usb_rx_buffer[2];
        velocidad = usb_rx_buffer[3];

        // Avanzamos el puntero para leer el siguiente paquete si lo hay
        usb_rx_buffer += 4;
        usb_rx_buffer_length -= 4;


        // Si es un mensaje NOTE ON (0x9) y la velocidad (volumen) es mayor que 0
        if (message == 0x9 && velocidad > 0) {

            // 1. Calcular la frecuencia de la nota (fórmula matemática de la música)
            float frecuencia = 440.0f * pow(2.0f, ((nota - 69) / 12.0f));

            // 2. Calcular el periodo para el Timer (Sabiendo que el reloj va a 80MHz)
            uint32_t ciclosperiodo = (uint32_t)(80000000.0f / frecuencia);

            // 3. Calculo el ciclo de trabajo para el volumen.
            uint32_t ciclosAlto = (ciclosperiodo / 2) * velocidad / 127;

            // 4. Escribir los valores en los registros del Timer 2
            __HAL_TIM_SET_AUTORELOAD(&htim2, ciclosperiodo);
            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, ciclosAlto);

            // 5. Arrancar el Timer 2 en modo PWM
            HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);

        }
        // Si es un mensaje NOTE OFF (0x8) o un NOTE ON con velocidad 0
        else if (message == 0x8 || (message == 0x9 && velocidad == 0)) {

            // Silenciamos el altavoz poniendo el ciclo de trabajo a 0
            __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 0);
        }
    }
}
